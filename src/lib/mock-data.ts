type RawProduct = Omit<Product, "id" | "slug" | "gradient" | "createdAt" | "rating" | "reviewCount"> & {
  rating: number;
  reviewCount: number;
  daysAgo: number;
};

function daysAgoIso(days: number) {
  const d = new Date();
  d.setDate(d.getDate() - days);
  return d.toISOString();
}

function build(raw: RawProduct): Product {
  const slug = slugify(`${raw.name} ${raw.selectedStorage ?? raw.storageOptions?.[0] ?? ""}`);
  return {
    ...raw,
    id: slug,
    slug,
    gradient: CATEGORY_META[raw.category].gradient,
    createdAt: daysAgoIso(raw.daysAgo),
  };
}


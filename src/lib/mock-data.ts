function buildTrackingSteps(status: Order["status"], placedDaysAgo: number): Order["trackingSteps"] {
  const order: Order["status"][] = ["Processing", "Quality Check", "Dispatched", "Out for Delivery", "Delivered"];
  const statusIndex = order.indexOf(status);
  return order.map((s, i) => ({
    status: s,
    label: s,
    complete: i <= statusIndex,
    timestamp: i <= statusIndex ? daysAgoIso(placedDaysAgo - i) : null,
  }));
}

